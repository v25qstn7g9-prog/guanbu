// Rebuilds public/ziwei-engine.js from ziwei-engine/. Run: npm run build:ziwei
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));

const banner = `/*! Guanbu Zi Wei engine bundle — generated by ziwei-engine/build.mjs, do not edit.
 * Chart engine: Renhuai123/ziwei-doushu lib/ziwei (MIT, Copyright (c) 2026 紫微研究) https://github.com/Renhuai123/ziwei-doushu
 * Includes iztro (MIT, SylarLong) https://github.com/SylarLong/iztro
 * Includes lunar-javascript (MIT, 6tail) https://github.com/6tail/lunar-javascript
 */`;

await build({
  entryPoints: [path.join(root, 'entry.ts')],
  outfile: path.join(root, '..', 'public', 'ziwei-engine.js'),
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'GuanbuZiwei',
  target: ['es2019'],
  legalComments: 'none',
  banner: { js: banner },
  logLevel: 'info',
});
